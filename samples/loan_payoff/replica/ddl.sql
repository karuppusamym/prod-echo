-- SYNTHETIC replica schema for the loan_payoff rehearsal (Postgres 17).
-- Shaped like the pilot replicas: upper-case names, a schema per application, one declared FK
-- missing (CUST_ADDR -> CUST_MSTR is by column name only), a composite key, local-time naive
-- timestamps, NUMERIC money and NUMERIC(10,0) account numbers.
CREATE SCHEMA lpo;

CREATE TABLE lpo."CUST_MSTR" (
  "CUST_ID"     VARCHAR(10) PRIMARY KEY,
  "FIRST_NM"    VARCHAR(40) NOT NULL,
  "LAST_NM"     VARCHAR(40) NOT NULL,
  "FULL_NAME"   VARCHAR(81) NOT NULL,
  "SSN"         CHAR(11),
  "DOB"         DATE,
  "EMAIL"       VARCHAR(120),
  "PHONE"       VARCHAR(20),
  "CREATED_TS"  TIMESTAMP NOT NULL,
  "LAST_MOD_TS" TIMESTAMP NOT NULL
);

CREATE TABLE lpo."CUST_ADDR" (
  "CUST_ID"     VARCHAR(10) NOT NULL,
  "ADDR_SEQ"    SMALLINT NOT NULL,
  "LINE1"       VARCHAR(80),
  "CITY"        VARCHAR(40),
  "POSTCODE"    VARCHAR(10),
  "LAST_MOD_TS" TIMESTAMP NOT NULL,
  PRIMARY KEY ("CUST_ID", "ADDR_SEQ")
);

CREATE TABLE lpo."REF_PAYOFF_REASON" (
  "REASON_CD" VARCHAR(4) PRIMARY KEY,
  "DESCR"     VARCHAR(60) NOT NULL
);

CREATE TABLE lpo."LOAN_ACCT" (
  "LOAN_NO"       NUMERIC(10, 0) PRIMARY KEY,
  "CUST_ID"       VARCHAR(10) NOT NULL REFERENCES lpo."CUST_MSTR" ("CUST_ID"),
  "PRODUCT_CD"    VARCHAR(4) NOT NULL,
  "PRINCIPAL_BAL" NUMERIC(15, 2) NOT NULL,
  "RATE_PCT"      NUMERIC(7, 4) NOT NULL,
  "OPEN_DT"       DATE NOT NULL,
  "STATUS_CD"     CHAR(1) NOT NULL,
  "LAST_MOD_TS"   TIMESTAMP NOT NULL
);

CREATE TABLE lpo."PAYOFF_QUOTE" (
  "QUOTE_ID"    BIGINT PRIMARY KEY,
  "LOAN_NO"     NUMERIC(10, 0) NOT NULL REFERENCES lpo."LOAN_ACCT" ("LOAN_NO"),
  "REASON_CD"   VARCHAR(4) NOT NULL REFERENCES lpo."REF_PAYOFF_REASON" ("REASON_CD"),
  "PAYOFF_DT"   DATE NOT NULL,
  "QUOTE_AMT"   NUMERIC(15, 2) NOT NULL,
  "PER_DIEM"    NUMERIC(9, 2),
  "CREATED_BY"  VARCHAR(30) NOT NULL,
  "CREATED_TS"  TIMESTAMP NOT NULL,
  "LAST_MOD_TS" TIMESTAMP NOT NULL
);
